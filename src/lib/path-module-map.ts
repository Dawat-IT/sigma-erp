export function resolveModuleFromPath(pathSegments: string[]): string | null {
  const path = pathSegments.join("/");
  if (PATH_TO_MODULE[path]) return PATH_TO_MODULE[path];
  // single segment fallback
  if (pathSegments.length === 1 && MODULE_REGISTRY[pathSegments[0]]) {
    return pathSegments[0];
  }
  return null;
}

export function allNavHrefs(): string[] {
  return flattenNav().map((n) => n.href);
}
